export function parseVotersCSV(csvText: string): Voter[] {
  const lines = csvText.trim().split(/\r?\n/);
  const voters: Voter[] = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    
    // Skip headers or title rows
    if (
      line.startsWith('Daftar') ||
      line.startsWith('SMK') ||
      line.toLowerCase().startsWith('no,') ||
      line.startsWith(',,,,,')
    ) {
      continue;
    }

    const parts = line.split(',').map((p) => p.trim());
    if (parts.length >= 6) {
      const no = parseInt(parts[0], 10);
      const nama = parts[1];
      const rombel = parts[2];
      const nipd = parts[3];
      const jk = (parts[4].toUpperCase() === 'L' ? 'L' : 'P') as 'L' | 'P';
      const nisn = parts[5];

      if (!isNaN(no) && nama && nisn) {
        // Unique token generated deterministically for offline token slip option: e.g. TKN-12207
        const token = `VOTE-${nipd || no}-${nisn.slice(-4)}`;
        voters.push({
          no,
          nama,
          rombel,
          nipd,
          jk,
          nisn,
          hasVoted: false,
          token,
        });
      }
    }
  }

  return voters;
}

export const INITIAL_VOTERS = parseVotersCSV(INITIAL_STUDENTS_CSV);
